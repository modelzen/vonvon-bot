import {randomUUID} from 'node:crypto';
import {mkdtemp,realpath,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {afterEach,beforeEach,expect,it} from 'vitest';
import {canonicalizeRichRecipeContent,digestRichRecipeContent, type RecipeRichContent} from '@vonvon/protocol';
import {selectRecipeSkills} from '../src/recipe/rich-skill-selection';
import {stageRichRecipeGeneration,openRichRecipeGeneration,openRichRecipeGenerationMetadata} from '../src/recipe/rich-generation';
let scratch:string;
beforeEach(async()=>{scratch=await realpath(await mkdtemp(join(tmpdir(),'metadata-boundary-')));});
afterEach(async()=>{await rm(scratch,{recursive:true,force:true});});
const ident=()=>({itemId:randomUUID(),originId:randomUUID()});
const text=(value:string)=>({kind:'inline' as const,value});
it('metadata opener accepts all manifest sizes accepted by full generation',async()=>{
 const files=Array.from({length:64},(_,i)=>({...ident(),name:i===0?'SKILL.md':String(i).padStart(3,'0')+'x'.repeat(228)+'.md',use:i===0?'skillDescription' as const:'reference' as const,text:text(i<8?'x'.repeat(114000):'short')}));
 const skills=Array.from({length:16},(_,i)=>({...ident(),name:'skill'+i,entryFileId:files[0]!.itemId,fileIds:files.map(f=>f.itemId)}));
 const field=(value:string)=>({...ident(),value});
 const content:RecipeRichContent={format:'rich-v2',schemaVersion:2,public:{name:field('name'),summary:field('summary'),overview:field('"'.repeat(32000)),version:field('1')},settings:[],rules:[],tasks:[],setup:[],memories:[],files,skills,parts:[]};
 const baseline=canonicalizeRichRecipeContent(content);
 const effective=selectRecipeSkills({skills,files},content.public).graph;
 expect(Buffer.byteLength(baseline.canonicalUTF8)).toBeLessThanOrEqual(1048576);
 expect(Buffer.byteLength(effective.canonicalUTF8)).toBeLessThanOrEqual(1048576);
 expect(Buffer.byteLength(baseline.canonicalUTF8)+Buffer.byteLength(effective.canonicalUTF8)).toBeGreaterThan(1048576+131072);
 expect(baseline.logicalBytes).toBeLessThanOrEqual(1048576);
 expect(effective.logicalBytes).toBeLessThanOrEqual(1048576);
 const release={format:'rich-v2' as const,recipeId:randomUUID(),versionId:randomUUID(),authorId:randomUUID(),revision:1,access:'direct' as const,contentSha256:await digestRichRecipeContent(baseline),logicalBytes:baseline.logicalBytes};
 const botDataRoot=scratch;
 const slot={botDataRoot,installationId:randomUUID(),generationId:randomUUID()};
 const staged=await stageRichRecipeGeneration({...slot,release,canonicalUTF8:baseline.canonicalUTF8,readMember:async()=>{throw new Error('no parts expected')},effectiveSkills:{skills,files}});
 expect((await openRichRecipeGeneration({...slot,expected:staged.pointer})).pointer).toEqual(staged.pointer);
 const metadata=await openRichRecipeGenerationMetadata({...slot,expected:staged.pointer});
 expect(metadata.skills).toEqual(skills);
 expect(metadata.files.map(file=>file.itemId)).toEqual(files.map(file=>file.itemId));
 await expect(metadata.readFiles([])).resolves.toEqual(new Map());
},20000);
