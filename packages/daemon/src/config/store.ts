import { homedir } from 'node:os';
import { chmod, mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { dirname } from 'node:path';
import { paths } from './paths';
import type { AppConfig, AppPreferences, TenantBrand } from './schema';
import { secretKeyForApp } from './schema';
import { migrateProviderId } from '../provider/model';

export async function loadConfig(path: string = paths.configFile): Promise<Partial<AppConfig>> {
  try {
    const text = await readFile(path, 'utf8');
    return migratePreferences(JSON.parse(text) as Partial<AppConfig>);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return {};
    throw err;
  }
}

function migratePreferences(cfg: Partial<AppConfig>): Partial<AppConfig> {
  const prefs = cfg.preferences;
  if (typeof prefs?.comments?.backend === 'string') prefs.comments.backend = migrateProviderId(prefs.comments.backend);
  const byBackend = prefs?.sessionTitles?.byBackend;
  if (byBackend && typeof byBackend === 'object') {
    const migrated: typeof byBackend = {};
    for (const [id, policy] of Object.entries(byBackend)) if (migrateProviderId(id) === id) migrated[id] = policy;
    // An entry already stored under the new id was written after the upgrade, so it outranks the legacy one.
    for (const [id, policy] of Object.entries(byBackend)) migrated[migrateProviderId(id)] ??= policy;
    prefs!.sessionTitles!.byBackend = migrated;
  }
  return cfg;
}

/**
 * Build an AppConfig whose secret is an exec-provider SecretRef pointing at
 * the local keystore via the secrets-getter wrapper. Bridge short-circuits
 * the spawn and reads the keystore directly; lark-cli can read the same way.
 */
export async function buildEncryptedAccountConfig(
  appId: string,
  tenant: TenantBrand,
  preferences?: AppPreferences,
): Promise<AppConfig> {
  const wrapperPath = await ensureSecretsGetterWrapper();
  return {
    accounts: {
      app: {
        id: appId,
        secret: { source: 'exec', provider: 'bridge', id: secretKeyForApp(appId) },
        tenant,
      },
    },
    secrets: {
      providers: {
        bridge: process.platform === 'win32'
          ? { source: 'exec', command: process.execPath, args: [process.argv[1] ?? '', 'secrets', 'get'], env: { HOME: homedir(), USERPROFILE: homedir(), VONVON_HOME: paths.appDir } }
          : { source: 'exec', command: wrapperPath, args: [] },
      },
    },
    ...(preferences ? { preferences } : {}),
  };
}

/**
 * Write the secrets-getter wrapper pointing at the current node + bridge
 * entry. Always rewrites (node path can move). 0700 perms.
 */
export async function ensureSecretsGetterWrapper(): Promise<string> {
  const wrapperPath = paths.secretsGetterScript;
  const node = process.execPath;
  const bridgeEntry = process.argv[1] ?? '';
  const sq = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`;
  const content =
    `#!/bin/sh\n` +
    `# Auto-generated by feishu-codex-bridge. Do not edit.\n` +
    `VONVON_HOME=${sq(paths.appDir)}; export VONVON_HOME\n` +
    `exec ${sq(node)} ${sq(bridgeEntry)} secrets get "$@"\n`;
  await mkdir(dirname(wrapperPath), { recursive: true });
  const tmp = `${wrapperPath}.tmp-${process.pid}`;
  await writeFile(tmp, content, 'utf8');
  await chmod(tmp, 0o700);
  await rename(tmp, wrapperPath);
  return wrapperPath;
}

// 同进程内并发 saveConfig 串行化 + tmp 唯一名：避免两次写共用 tmp 文件交错（rename
// 命中被对方写一半的 tmp → JSON 损坏，或丢写）。
let saveChain: Promise<unknown> = Promise.resolve();
export function saveConfig(cfg: AppConfig, path: string = paths.configFile, expected?: AppConfig): Promise<void> {
  const run = saveChain.then(async () => {
    if (expected && JSON.stringify(await loadConfig(path)) !== JSON.stringify(expected)) throw new Error('配置已被其他进程修改，请重启 Host 后重新加载');
    await mkdir(dirname(path), { recursive: true });
    const tmp = `${path}.tmp-${process.pid}-${randomUUID()}`;
    await writeFile(tmp, `${JSON.stringify(cfg, null, 2)}\n`, 'utf8');
    await chmod(tmp, 0o600);
    await rename(tmp, path);
  });
  saveChain = run.then(
    () => undefined,
    () => undefined,
  );
  return run;
}
