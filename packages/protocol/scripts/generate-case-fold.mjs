import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';

const source = new URL('./unicode-15.1.0/CaseFolding.txt', import.meta.url);
const output = new URL('../src/unicode-full-case-fold.generated.ts', import.meta.url);
const bytes = readFileSync(source);
const sha256 = '4e55acfdc32825a22e87670e9056a3bf94ad7c5400065778e9e10f8314372bcf';
if (createHash('sha256').update(bytes).digest('hex') !== sha256) throw new Error('Unicode 15.1.0 CaseFolding.txt checksum mismatch');

const entries = [];
for (const line of bytes.toString('utf8').split('\n')) {
  const [code, status, mapping] = line.split(';').map(field => field.trim());
  if (status !== 'C' && status !== 'F') continue;
  const escapes = mapping.split(' ').map(hex => '\\u{' + hex + '}').join('');
  entries.push("0x" + code + ": '" + escapes + "',");
}
const lines = [];
for (let i = 0; i < entries.length; i += 4) lines.push('  ' + entries.slice(i, i + 4).join(' '));
const generated = [
  '/*! Unicode 15.1.0 CaseFolding.txt © 2023 Unicode, Inc. See LICENSE.UNICODE. Generated by scripts/generate-case-fold.mjs. */',
  'export const fullCaseFold: Readonly<Record<number, string | undefined>> = {', ...lines, '};', '',
].join('\n');
if (process.argv.length === 2) writeFileSync(output, generated);
else if (process.argv.length !== 3 || process.argv[2] !== '--check') throw new Error('Usage: node generate-case-fold.mjs [--check]');
else if (readFileSync(output, 'utf8') !== generated) throw new Error('Regenerate unicode-full-case-fold.generated.ts');
